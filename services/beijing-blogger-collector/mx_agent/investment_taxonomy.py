def classify_text(text: str) -> list[str]:
    return [
        slug
        for _, _, _, children in TAXONOMY
        for slug, _, _, pattern in children
        if re.search(pattern, text, re.IGNORECASE)
    ]


def taxonomy_counts() -> tuple[int, int]:
    return len(TAXONOMY), sum(len(children) for _, _, _, children in TAXONOMY)
